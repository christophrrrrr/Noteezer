"""Writes a service's OpenAPI document to openapi.yaml, or checks that it is current.

FastAPI builds the document from the routes and models, so the file is never
written by hand. CI runs this with --check and fails when someone changed an
endpoint without regenerating the file (README, Tests).

Run it from a service's folder, with that service's packages installed:

    cd services/inbox
    python ../../scripts/openapi.py            # rewrite openapi.yaml
    python ../../scripts/openapi.py --check    # exit 1 if it is out of date
"""

import os
import sys
from pathlib import Path

import yaml

HERE = Path.cwd()
TARGET = HERE / "openapi.yaml"


def document() -> str:
    # The app is only built, never started, so no database is needed. The
    # variables only have to exist for create_app() to run.
    os.environ.setdefault("SESSION_SECRET", "unused")
    os.environ.setdefault("SORTER", "rules")
    sys.path.insert(0, str(HERE))
    from app.main import create_app

    schema = create_app().openapi()
    header = "# Generated by scripts/openapi.py from the code. Do not edit by hand.\n"
    return header + yaml.safe_dump(schema, sort_keys=False, allow_unicode=True, width=120)


def main() -> int:
    text = document()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET} is out of date. Run: python ../../scripts/openapi.py", file=sys.stderr)
            return 1
        print(f"{TARGET.name} matches the code.")
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
